"""Export Merlin's read-only small decoder and regenerate the committed unsupported-op report.

MERLIN_ROOT=/path/to/merlin TORCH_PYTHON=/path/to/torch/python \
  python3 -B coverage/examples/causal_decoder/regenerate.py --out /path/to/output

The driver Python needs PyYAML; TORCH_PYTHON needs torch and NumPy. Full inventories and graphs
remain under --out. Only the concise REPORT.md is written alongside this script.
"""
from __future__ import annotations

import argparse
import json
import os
from pathlib import Path
import subprocess
import sys
import tempfile

HERE = Path(__file__).absolute().parent
COVERAGE = HERE.parents[1]


def render(fixture, summary):
    model = summary['models']['causal_decoder']
    rows = model['unmapped']
    lines = [
        '# causal_decoder unsupported-op example', '',
        'Generated by `MERLIN_ROOT=/path/to/merlin TORCH_PYTHON=/path/to/torch/python '
        'python3 -B coverage/examples/causal_decoder/regenerate.py --out "$OUT"`.', '',
        'Source: `merlin:examples/workloads/causal_decoder/loader.py`, SHA-256 '
        f"`{fixture['sources']['loader']['sha256']}`. The adapter returns a deterministic small decoder "
        'and an 8-token input; it needs no checkpoint or download.', '',
        f"Export: `{fixture['method']}`, {fixture['node_count']} ATen records, {len(fixture['ops'])} aggregated rows, "
        f"{sum(row['count'] for row in fixture['ops'] if row['op'] in ('aten.linear.default', 'aten.conv2d.default', 'aten.conv2d.padding'))} "
        f"projection invocations, and {sum(row['count'] for row in fixture['ops'] if row['op'] in ('aten.softmax.int', 'aten.scaled_dot_product_attention.default'))} attention core.", '',
        f"**{model['status']}: {len(rows)} unmapped rows, {sum(row['count'] for row in rows)} op instances, "
        f"{model['flops']['unmapped']:,} FLOPs.** No placement rules or qualified Atlas build are registered "
        'for this decoder. These operations require implementation and qualification; this report demonstrates '
        'inventory and unsupported-op reporting. Real-value capture and model execution on Atlas have not run.', '',
        'The regeneration command runs `export_ops.py causal_decoder --loader ...` and '
        '`build_table.py --inventory causal_decoder=... --allow-unmapped`. The full JSON report retains '
        'each input shape, output shape, dtype, phase, source, count, and FLOP estimate under the printed output directory. '
        'Without `--allow-unmapped`, the table builder exits nonzero.', '',
        '| module | source | op | output shape and dtype | count | FLOPs |',
        '| --- | --- | --- | --- | ---: | ---: |',
    ]
    for row in rows:
        shape, dtype = row['outputs'][0] if row['outputs'] else ([], '')
        output = 'x'.join(map(str, shape)) or 'scalar'
        lines.append(f"| `{row['module'] or '(top)'}` | `{row['source']}` | `{row['op']}` | "
                     f"{output} {dtype} | {row['count']} | {row['count'] * row['flops_each']:,} |")
    return '\n'.join(lines) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--merlin-root', type=Path, default=os.environ.get('MERLIN_ROOT'))
    parser.add_argument('--torch-python', default=os.environ.get('TORCH_PYTHON', sys.executable))
    parser.add_argument('--out', type=Path, required=True)
    parser.add_argument('--report', type=Path, default=HERE / 'REPORT.md')
    args = parser.parse_args()
    if args.merlin_root is None:
        parser.error('set MERLIN_ROOT or pass --merlin-root')
    args.out.mkdir(parents=True, exist_ok=True)
    run = Path(tempfile.mkdtemp(prefix='causal-decoder-', dir=args.out))
    fixture = run / 'fixture.json'
    environment = dict(os.environ, PYTHONDONTWRITEBYTECODE='1')
    subprocess.run([args.torch_python, '-B', str(COVERAGE / 'export_ops.py'), 'causal_decoder', '--loader',
                    str(args.merlin_root / 'examples/workloads/causal_decoder/loader.py'), '--out', str(run / 'export'),
                    '--fixture', str(fixture)], env=environment, check=True)
    subprocess.run([sys.executable, '-B', str(COVERAGE / 'build_table.py'), '--inventory',
                    f'causal_decoder={fixture}', '--allow-unmapped', '--out', str(run / 'report')],
                   env=environment, check=True)
    inventory = json.loads(fixture.read_text())
    summary = json.loads((run / 'report' / 'coverage.json').read_text())
    args.report.write_text(render(inventory, summary))
    print(f'Full export and placement reports: {run}')
    print(f'Concise unsupported-op report: {args.report}')


if __name__ == '__main__':
    main()
